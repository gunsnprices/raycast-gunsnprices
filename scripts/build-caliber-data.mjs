// Writes src/lib/caliber-data.ts: store spellings and listing counts for each caliber, taken from the installed
// gunsnprices package. The package's public API gives id, name, type and url; this adds what search needs.
// Run after upgrading gunsnprices: npm run data
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
// the package exports only its entry point (src/index.js), so walk up from there
const pkgDir = dirname(dirname(require.resolve("gunsnprices")));
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
const { default: DATA } = await import(pathToFileURL(join(pkgDir, "src/data/calibers.js")).href);

const out = {};
for (const c of DATA.calibers) {
  const seen = new Set([c.name.toLowerCase()]);
  const spellings = [];
  for (const s of [c.site_name, ...c.aliases]) {
    const k = s.toLowerCase();
    if (!seen.has(k)) {
      seen.add(k);
      spellings.push(s);
    }
  }
  out[c.id] = { spellings, listings: c.n || 0 };
}

const body =
  `// Generated by scripts/build-caliber-data.mjs from gunsnprices ${pkg.version}. Do not edit.\n` +
  `// Data: GunsNPrices caliber list, CC BY 4.0 (https://gunsnprices.com).\n` +
  `export const DATA_VERSION = ${JSON.stringify(pkg.version)};\n\n` +
  `export const CALIBER_DATA: Record<string, { spellings: string[]; listings: number }> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(new URL("../src/lib/caliber-data.ts", import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} calibers from gunsnprices ${pkg.version}`);
